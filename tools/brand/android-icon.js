#!/usr/bin/env node
// Writes the Android launcher icon layers (adaptive icon, 108dp canvas) from the same geometry as
// assets/brand/mark.svg: ic_launcher_foreground, ic_launcher_background and ic_launcher_monochrome.
// The mark is scaled so everything except the soft glow sits inside the 66dp safe zone.
//   node tools/brand/android-icon.js
'use strict';
const fs = require('fs');
const path = require('path');

const res = path.join(__dirname, '..', '..', 'app', 'src', 'main', 'res', 'drawable');
const S = 0.18; // 512-unit logo space -> 108dp canvas, centred on 54
const P = (v) => +(54 + (v - 256) * S).toFixed(2);
const L = (v) => +(v * S).toFixed(2);
const circle = (cx, cy, r) =>
  `M${P(cx) - L(r)},${P(cy)} a${L(r)},${L(r)} 0 1,0 ${2 * L(r)},0 a${L(r)},${L(r)} 0 1,0 ${-2 * L(r)},0`;
// The C: radius 150, open on the right between -38 and +38 degrees.
const ring = `M${P(374.2)},${P(163.7)} A${L(150)},${L(150)} 0 1,0 ${P(374.2)},${P(348.3)}`;
const shine = `M${P(362)},${P(176)} A${L(132)},${L(132)} 0 0,0 ${P(124)},${P(256)}`;

const head = (extra = '') => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/android-icon.js from assets/brand/mark.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${extra}
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">`;
const AAPT = `\n    xmlns:aapt="http://schemas.android.com/aapt"`;
const linear = (attr, x1, y1, x2, y2, stops) => `
        <aapt:attr name="${attr}">
            <gradient android:type="linear" android:startX="${x1}" android:startY="${y1}" android:endX="${x2}" android:endY="${y2}">
${stops.map(([o, c]) => `                <item android:offset="${o}" android:color="${c}"/>`).join('\n')}
            </gradient>
        </aapt:attr>`;
const radial = (attr, cx, cy, r, stops) => `
        <aapt:attr name="${attr}">
            <gradient android:type="radial" android:centerX="${cx}" android:centerY="${cy}" android:gradientRadius="${r}">
${stops.map(([o, c]) => `                <item android:offset="${o}" android:color="${c}"/>`).join('\n')}
            </gradient>
        </aapt:attr>`;

const foreground = `${head(AAPT)}
    <!-- C ring -->
    <path android:pathData="${ring}" android:strokeWidth="${L(66)}" android:strokeLineCap="round" android:fillColor="#00000000">${linear('android:strokeColor', P(123), P(91), P(357), P(421), [[0, '#FFF4EFFF'], [0.45, '#FFB8A4FF'], [1, '#FFFF8FB8']])}
    </path>
    <path android:pathData="${shine}" android:strokeWidth="${L(10)}" android:strokeLineCap="round" android:fillColor="#00000000" android:strokeColor="#40FFFFFF"/>
    <!-- Lens -->
    <path android:pathData="${circle(256, 256, 80)}" android:fillColor="#FF120E22" android:strokeColor="#BFC9BBFF" android:strokeWidth="${L(5)}"/>
    <path android:pathData="${circle(256, 256, 64)}">${radial('android:fillColor', P(238), P(233), L(102), [[0, '#FF9C86FF'], [0.45, '#FF4A3699'], [1, '#FF140F28']])}
    </path>
    <path android:pathData="${circle(256, 256, 32)}" android:fillColor="#FF05040A"/>
    <group android:rotation="-35" android:pivotX="${P(233)}" android:pivotY="${P(228)}">
        <path android:pathData="M${P(233) - L(17)},${P(228)} a${L(17)},${L(10)} 0 1,0 ${2 * L(17)},0 a${L(17)},${L(10)} 0 1,0 ${-2 * L(17)},0" android:fillColor="#BFFFFFFF"/>
    </group>
    <path android:pathData="${circle(281, 282, 5)}" android:fillColor="#59FFFFFF"/>
    <!-- REC dot -->
    <path android:pathData="${circle(410, 256, 50)}">${radial('android:fillColor', P(410), P(256), L(50), [[0, '#8CFF3D63'], [1, '#00FF3D63']])}
    </path>
    <path android:pathData="${circle(410, 256, 28)}">${radial('android:fillColor', P(403), P(246), L(42), [[0, '#FFFF9EB0'], [0.6, '#FFFF3D63'], [1, '#FFD81B45']])}
    </path>
</vector>
`;

const background = `${head(AAPT)}
    <path android:pathData="M0,0h108v108h-108z">${linear('android:fillColor', 0, 0, 108, 108, [[0, '#FF33275F'], [0.6, '#FF1B1B22'], [1, '#FF121019']])}
    </path>
    <path android:pathData="M0,0h108v108h-108z">${radial('android:fillColor', 35, 32, 76, [[0, '#59B8A4FF'], [1, '#00B8A4FF']])}
    </path>
</vector>
`;

// Single colour, for themed icons and the notification icon.
const monochrome = `${head()}
    <path android:pathData="${ring}" android:strokeWidth="${L(66)}" android:strokeLineCap="round" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"/>
    <path android:pathData="${circle(256, 256, 64)}" android:fillColor="#FFFFFFFF"/>
    <path android:pathData="${circle(410, 256, 28)}" android:fillColor="#FFFFFFFF"/>
</vector>
`;

fs.writeFileSync(path.join(res, 'ic_launcher_foreground.xml'), foreground);
fs.writeFileSync(path.join(res, 'ic_launcher_background.xml'), background);
fs.writeFileSync(path.join(res, 'ic_launcher_monochrome.xml'), monochrome);
console.log('wrote ic_launcher_foreground, ic_launcher_background, ic_launcher_monochrome');
